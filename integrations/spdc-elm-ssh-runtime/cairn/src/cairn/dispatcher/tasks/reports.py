from __future__ import annotations

from pathlib import PurePosixPath

from cairn.dispatcher.runtime.environments.base import EnvironmentHandle, WorkEnvironment


def build_report_path(handle: EnvironmentHandle, intent_id: str, run_id: str | None = None) -> str:
    suffix = f"{intent_id}-{run_id}" if run_id else intent_id
    return str(PurePosixPath(handle.workspace) / ".cairn" / "reports" / f"execution-{suffix}.md")


def report_instruction(report_path: str) -> str:
    return (
        "Before returning your final JSON, write a Markdown execution report to this exact path:\n\n"
        f"{report_path}\n\n"
        "Keep the JSON fact description short. Put commands, evidence, artifacts, failures, and uncertainty in the report."
    )


def validate_report_written(environment: WorkEnvironment, handle: EnvironmentHandle, report_path: str) -> bool:
    return environment.is_path_in_workspace(handle, report_path) and environment.exists(handle, report_path)


def write_failure_report(
    environment: WorkEnvironment,
    handle: EnvironmentHandle,
    report_path: str,
    *,
    intent_id: str,
    worker: str,
    run_id: str | None,
    reason: str,
    details: str = "",
) -> None:
    body = "\n".join(
        [
            "# Execution Report",
            "",
            "## Intent",
            intent_id,
            "",
            "## Summary",
            "The run did not produce a successful fact.",
            "",
            "## Failures And Dead Ends",
            f"- worker: {worker}",
            f"- run_id: {run_id or 'unknown'}",
            f"- reason: {reason}",
            f"- details: {details}" if details else "- details: unavailable",
            "",
            "## Uncertainty",
            "Retry or edit the intent after reviewing dispatcher logs and workspace artifacts.",
            "",
        ]
    )
    environment.write_text_file(handle, report_path, body)


def write_autogenerated_report(
    environment: WorkEnvironment,
    handle: EnvironmentHandle,
    report_path: str,
    *,
    intent_id: str,
    worker: str,
    run_id: str | None,
    title: str | None,
    description: str,
    reason: str,
) -> None:
    body = "\n".join(
        [
            "# Execution Report",
            "",
            "## Intent",
            intent_id,
            "",
            "## Summary",
            description,
            "",
            "## Result Title",
            title or "Untitled result",
            "",
            "## Dispatcher Notes",
            f"- worker: {worker}",
            f"- run_id: {run_id or 'unknown'}",
            f"- reason: {reason}",
            "- report_source: dispatcher_autogenerated",
            "",
            "## Uncertainty",
            "The worker returned a valid JSON result but did not write the requested Markdown report. "
            "Review the run log for raw stdout, stderr, and tool events.",
            "",
        ]
    )
    environment.write_text_file(handle, report_path, body)


def metadata_for_report(
    report_path: str,
    report_run_id: str | None,
    worker: str,
    intent_id: str,
    *,
    producing_run_log_id: str | None = None,
) -> dict:
    return {
        "report_path": report_path,
        "report_run_id": report_run_id,
        "worker": worker,
        "intent_id": intent_id,
        "provenance": {
            "producing_intent_id": intent_id,
            "producing_run_log_id": producing_run_log_id,
            "report_run_id": report_run_id,
            "report_path": report_path,
            "worker_name": worker,
        },
    }


def metadata_for_worker_fact(
    worker: str,
    intent_id: str,
    *,
    producing_run_log_id: str | None = None,
) -> dict:
    return {
        "worker": worker,
        "intent_id": intent_id,
        "provenance": {
            "producing_intent_id": intent_id,
            "producing_run_log_id": producing_run_log_id,
            "report_run_id": None,
            "report_path": None,
            "worker_name": worker,
        },
    }
